CREATE OR REPLACE TABLE ACCOUNT_SNAPSHOT AS
WITH accounts AS (
  SELECT
    ACCOUNT_ORDINAL + 1 AS ACCOUNT_NUMBER,
    'ACCT-' || LPAD((ACCOUNT_ORDINAL + 1)::VARCHAR, 7, '0') AS ACCOUNT_ID
  FROM (
    SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS ACCOUNT_ORDINAL
    FROM TABLE(GENERATOR(ROWCOUNT => {{ACCOUNT_COUNT}}))
  )
), months AS (
  SELECT
    MONTH_ORDINAL AS MONTH_NUMBER,
    DATEADD(MONTH, MONTH_ORDINAL, '{{FIRST_OBSERVATION_MONTH}}'::DATE) AS OBSERVATION_DATE
  FROM (
    SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS MONTH_ORDINAL
    FROM TABLE(GENERATOR(ROWCOUNT => {{OBSERVATION_MONTHS}}))
  )
), base AS (
  SELECT
    a.ACCOUNT_NUMBER,
    a.ACCOUNT_ID,
    m.MONTH_NUMBER,
    m.OBSERVATION_DATE,
    BITAND(HASH(a.ACCOUNT_NUMBER, {{DATA_SEED}}), 9223372036854775807) AS ACCOUNT_HASH,
    BITAND(HASH(a.ACCOUNT_NUMBER, m.MONTH_NUMBER, {{DATA_SEED}}), 9223372036854775807) AS MONTH_HASH
  FROM accounts a
  CROSS JOIN months m
)
SELECT
  ACCOUNT_ID,
  OBSERVATION_DATE,
  CASE MOD(ACCOUNT_HASH, 3)
    WHEN 0 THEN 'CREDIT_CARD'
    WHEN 1 THEN 'PERSONAL_LOAN'
    ELSE 'REVOLVING_CREDIT'
  END AS PRODUCT_TYPE,
  CASE MOD(FLOOR(ACCOUNT_HASH / 3), 3)
    WHEN 0 THEN 'BRANCH'
    WHEN 1 THEN 'DIGITAL'
    ELSE 'PARTNER'
  END AS ORIGINATION_CHANNEL,
  CASE
    WHEN 6 + MOD(ACCOUNT_HASH, 114) < 24 THEN 'UNDER_2Y'
    WHEN 6 + MOD(ACCOUNT_HASH, 114) < 60 THEN '2_TO_5Y'
    ELSE 'OVER_5Y'
  END AS TENURE_BAND,
  (6 + MOD(ACCOUNT_HASH, 114) + MONTH_NUMBER)::NUMBER(5,0) AS ACCOUNT_AGE_MONTHS,
  (1500 + MOD(ACCOUNT_HASH, 23500))::NUMBER(12,2) AS CREDIT_LIMIT,
  LEAST(
    1.25,
    GREATEST(
      0.01,
      0.16
      + MOD(MONTH_HASH, 5800) / 10000.0
      + IFF(OBSERVATION_DATE >= '{{DRIFT_START_DATE}}'::DATE, 0.11, 0)
      + 0.035 * SIN(MONTH_NUMBER / 3.0)
    )
  )::NUMBER(7,4) AS UTILISATION_RATIO,
  (900 + MOD(BITAND(HASH(ACCOUNT_NUMBER, {{DATA_SEED}} + 11), 9223372036854775807), 9100))::NUMBER(12,2)
    AS MONTHLY_INCOME_ESTIMATE,
  GREATEST(
    25,
    (120 + MOD(BITAND(HASH(ACCOUNT_NUMBER, MONTH_NUMBER, {{DATA_SEED}} + 17), 9223372036854775807), 1800))
      - IFF(OBSERVATION_DATE >= '{{DRIFT_START_DATE}}'::DATE, 70, 0)
  )::NUMBER(12,2) AS PAYMENT_AMOUNT_30D,
  IFF(
    MOD(BITAND(HASH(ACCOUNT_NUMBER, MONTH_NUMBER, {{DATA_SEED}} + 23), 9223372036854775807), 100)
      < 4 + IFF(OBSERVATION_DATE >= '{{DRIFT_START_DATE}}'::DATE, 3, 0),
    1,
    0
  )::NUMBER(1,0) AS MISSED_PAYMENT_30D,
  LEAST(
    3,
    IFF(MOD(BITAND(HASH(ACCOUNT_NUMBER, MONTH_NUMBER, {{DATA_SEED}} + 29), 9223372036854775807), 100) < 15, 1, 0)
      + IFF(MOD(BITAND(HASH(ACCOUNT_NUMBER, MONTH_NUMBER, {{DATA_SEED}} + 31), 9223372036854775807), 100) < 5, 1, 0)
      + IFF(OBSERVATION_DATE >= '{{DRIFT_START_DATE}}'::DATE
            AND MOD(BITAND(HASH(ACCOUNT_NUMBER, MONTH_NUMBER, {{DATA_SEED}} + 37), 9223372036854775807), 100) < 5, 1, 0)
  )::NUMBER(1,0) AS MISSED_PAYMENTS_6M,
  IFF(
    MOD(BITAND(HASH(ACCOUNT_NUMBER, MONTH_NUMBER, {{DATA_SEED}} + 41), 9223372036854775807), 100)
      < 6 + IFF(OBSERVATION_DATE >= '{{DRIFT_START_DATE}}'::DATE, 4, 0),
    1,
    0
  )::NUMBER(1,0) AS IN_ARREARS_30D,
  (MOD(BITAND(HASH(ACCOUNT_NUMBER, MONTH_NUMBER, {{DATA_SEED}} + 43), 9223372036854775807), 9))::NUMBER(2,0)
    AS CUSTOMER_CONTACTS_90D,
  IFF(OBSERVATION_DATE >= '{{DRIFT_START_DATE}}'::DATE, 'DRIFT', 'STABLE') AS DATA_SCENARIO,
  '{{AS_OF_DATE}} 00:00:00'::TIMESTAMP_NTZ AS GENERATED_AT
FROM base;

CREATE OR REPLACE TABLE DEFAULT_OUTCOME AS
WITH scored AS (
  SELECT
    s.*,
    -4.35
      + 2.30 * s.UTILISATION_RATIO
      + 0.95 * s.MISSED_PAYMENT_30D
      + 0.52 * s.MISSED_PAYMENTS_6M
      + 1.05 * s.IN_ARREARS_30D
      - 0.000055 * s.PAYMENT_AMOUNT_30D
      - 0.000025 * s.MONTHLY_INCOME_ESTIMATE
      + IFF(s.PRODUCT_TYPE = 'REVOLVING_CREDIT', 0.24, 0)
      + IFF(s.DATA_SCENARIO = 'DRIFT', 0.18, 0) AS LOG_ODDS,
    MOD(BITAND(HASH(s.ACCOUNT_ID, s.OBSERVATION_DATE, {{DATA_SEED}} + 97), 9223372036854775807), 1000000) / 1000000.0
      AS DRAW
  FROM ACCOUNT_SNAPSHOT s
)
SELECT
  ACCOUNT_ID,
  OBSERVATION_DATE,
  DATEADD(DAY, {{OUTCOME_WINDOW_DAYS}}, OBSERVATION_DATE)::DATE AS OUTCOME_FINALITY_DATE,
  IFF(DRAW < 1.0 / (1.0 + EXP(-LOG_ODDS)), 1, 0)::NUMBER(1,0) AS DEFAULT_WITHIN_90D,
  IFF(DATEADD(DAY, {{OUTCOME_WINDOW_DAYS}}, OBSERVATION_DATE) <= '{{AS_OF_DATE}}'::DATE,
      'FINALISED', 'PENDING') AS OUTCOME_STATUS,
  'Synthetic 90-day default outcome for technical demonstration only' AS OUTCOME_DEFINITION
FROM scored;

CREATE OR REPLACE VIEW AVAILABLE_GROUND_TRUTH AS
SELECT
  ACCOUNT_ID,
  OBSERVATION_DATE,
  OUTCOME_FINALITY_DATE,
  DEFAULT_WITHIN_90D
FROM DEFAULT_OUTCOME
WHERE OUTCOME_STATUS = 'FINALISED';

