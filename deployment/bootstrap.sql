-- Summarise the generated portfolio before releasing bootstrap compute.
SELECT
  COUNT(*) AS SNAPSHOT_ROWS,
  COUNT(DISTINCT ACCOUNT_ID) AS ACCOUNTS,
  MIN(OBSERVATION_DATE) AS FIRST_OBSERVATION,
  MAX(OBSERVATION_DATE) AS LAST_OBSERVATION,
  COUNT(DISTINCT OBSERVATION_DATE) AS OBSERVATION_MONTHS
FROM {{DATABASE}}.{{RAW_SCHEMA}}.ACCOUNT_SNAPSHOT;

SELECT
  COUNT(*) AS OUTCOME_ROWS,
  COUNT_IF(OUTCOME_STATUS = 'FINALISED') AS FINALISED_OUTCOMES,
  COUNT_IF(OUTCOME_STATUS = 'PENDING') AS PENDING_OUTCOMES,
  COUNT_IF(OUTCOME_STATUS = 'FINALISED' AND DEFAULT_WITHIN_90D = 1)
    AS FINALISED_DEFAULTS,
  AVG(IFF(OUTCOME_STATUS = 'FINALISED', DEFAULT_WITHIN_90D, NULL))
    AS FINALISED_DEFAULT_RATE,
  (SELECT COUNT(*) FROM {{DATABASE}}.{{RAW_SCHEMA}}.TRAINING_BASE)
    AS TRAINING_ROWS,
  (SELECT COUNT(*) FROM {{DATABASE}}.{{RAW_SCHEMA}}.SCORING_POPULATION)
    AS SCORING_ROWS
FROM {{DATABASE}}.{{RAW_SCHEMA}}.DEFAULT_OUTCOME;

SELECT
  s.DATA_SCENARIO,
  o.OUTCOME_STATUS,
  COUNT(*) AS SNAPSHOT_COUNT,
  AVG(s.UTILISATION_RATIO) AS AVG_UTILISATION_RATIO,
  AVG(s.MISSED_PAYMENT_30D) AS MISSED_PAYMENT_RATE_30D,
  AVG(s.MISSED_PAYMENTS_6M) AS AVG_MISSED_PAYMENTS_6M,
  AVG(s.IN_ARREARS_30D) AS ARREARS_RATE_30D,
  AVG(IFF(o.OUTCOME_STATUS = 'FINALISED', o.DEFAULT_WITHIN_90D, NULL))
    AS FINALISED_DEFAULT_RATE
FROM {{DATABASE}}.{{RAW_SCHEMA}}.ACCOUNT_SNAPSHOT s
JOIN {{DATABASE}}.{{RAW_SCHEMA}}.DEFAULT_OUTCOME o
  USING (ACCOUNT_ID, OBSERVATION_DATE)
GROUP BY s.DATA_SCENARIO, o.OUTCOME_STATUS
ORDER BY s.DATA_SCENARIO, o.OUTCOME_STATUS;

SELECT
  PRODUCT_TYPE,
  COUNT(*) AS SNAPSHOT_ROWS,
  COUNT(DISTINCT ACCOUNT_ID) AS ACCOUNTS,
  AVG(UTILISATION_RATIO) AS AVG_UTILISATION_RATIO,
  AVG(IN_ARREARS_30D) AS ARREARS_RATE_30D
FROM {{DATABASE}}.{{RAW_SCHEMA}}.ACCOUNT_SNAPSHOT
GROUP BY PRODUCT_TYPE
ORDER BY PRODUCT_TYPE;

