  ACCOUNT_ID VARCHAR COMMENT 'Facility identifier joining to DIM_CREDIT_ACCOUNT',
  SNAPSHOT_DATE DATE COMMENT 'Calendar date represented by this end-of-day servicing state',
  OUTSTANDING_BALANCE NUMBER(14,2) COMMENT 'End-of-day drawn principal balance in account currency units',
  CREDIT_LIMIT NUMBER(12,2) COMMENT 'Credit limit effective on SNAPSHOT_DATE',
  AVAILABLE_CREDIT NUMBER(14,2) COMMENT 'Non-negative undrawn credit available on SNAPSHOT_DATE',
  AMOUNT_DUE NUMBER(12,2) COMMENT 'Statement amount due at the latest billing cycle',
  MINIMUM_PAYMENT_DUE NUMBER(12,2) COMMENT 'Minimum contractual payment due',
  DAYS_PAST_DUE NUMBER(4,0) COMMENT 'Consecutive calendar days the facility is past due, capped at 120',
  ARREARS_AMOUNT NUMBER(12,2) COMMENT 'Overdue amount associated with the current delinquency state',
  ACCOUNT_STATUS VARCHAR COMMENT 'Servicing status on SNAPSHOT_DATE: CURRENT, DELINQUENT, or CHARGED_OFF',
  DATA_SCENARIO VARCHAR COMMENT 'Controlled source regime with values STABLE or DRIFT; excluded from model features',
  GENERATED_AT TIMESTAMP_NTZ COMMENT 'Timestamp when the source record was generated'
) COMMENT = 'Daily revolving-credit servicing state; one row per account and calendar date';

INSERT OVERWRITE INTO FACT_ACCOUNT_DAILY_SNAPSHOT
WITH calendar AS (
  SELECT SNAPSHOT_DATE
  FROM (
    SELECT DATEADD(DAY, DAY_NUMBER, DATEADD(MONTH, -12, '{{FIRST_OBSERVATION_MONTH}}'::DATE))
      AS SNAPSHOT_DATE
    FROM (
      SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS DAY_NUMBER
      FROM TABLE(GENERATOR(ROWCOUNT => {{DAILY_HISTORY_DAYS}}))
    )
  )
  WHERE SNAPSHOT_DATE <= '{{AS_OF_DATE}}'::DATE
), account_dates AS (
  SELECT
    a.ACCOUNT_ID,
    a.ORIGINAL_CREDIT_LIMIT,
    d.SNAPSHOT_DATE,
    DATEDIFF(DAY, DATEADD(MONTH, -12, '{{FIRST_OBSERVATION_MONTH}}'::DATE), d.SNAPSHOT_DATE) AS DAY_NUMBER,
    BITAND(HASH(a.ACCOUNT_ID, {{DATA_SEED}} + 29), 9223372036854775807) AS ACCOUNT_HASH,
    IFF(
      MOD(BITAND(HASH(a.ACCOUNT_ID, {{DATA_SEED}} + 31), 9223372036854775807), 100) < 14,
      DATEADD(
        DAY,
        420 + MOD(BITAND(HASH(a.ACCOUNT_ID, {{DATA_SEED}} + 37), 9223372036854775807), 700),
        DATEADD(MONTH, -12, '{{FIRST_OBSERVATION_MONTH}}'::DATE)
      ),
      NULL
    ) AS STRESS_START_DATE
  FROM DIM_CREDIT_ACCOUNT a
  CROSS JOIN calendar d
), delinquency_state AS (
  SELECT
    *,
    IFF(STRESS_START_DATE IS NULL OR SNAPSHOT_DATE < STRESS_START_DATE,
        0, LEAST(120, DATEDIFF(DAY, STRESS_START_DATE, SNAPSHOT_DATE))) AS DAYS_PAST_DUE_RAW,
    ORIGINAL_CREDIT_LIMIT * IFF(
      MOD(BITAND(HASH(ACCOUNT_ID, {{DATA_SEED}} + 23), 9223372036854775807), 4) = 0
      AND SNAPSHOT_DATE >= DATEADD(
        DAY,
        MOD(BITAND(HASH(ACCOUNT_ID, {{DATA_SEED}} + 59), 9223372036854775807), 700),
        DATEADD(MONTH, -9, '{{FIRST_OBSERVATION_MONTH}}'::DATE)
      ),
      1.10,
      1.00
    ) AS EFFECTIVE_LIMIT
  FROM account_dates
), states AS (
  SELECT
    *,
    LEAST(
      1.18,
      GREATEST(
        0.04,
        0.18 + MOD(ACCOUNT_HASH, 4200) / 10000.0
        + 0.025 * SIN(DAY_NUMBER / 30.0)
        + IFF(SNAPSHOT_DATE >= '{{DRIFT_START_DATE}}'::DATE, 0.08, 0)
        + 0.0035 * DAYS_PAST_DUE_RAW
      )
    ) AS UTILISATION
  FROM delinquency_state
)
SELECT
  ACCOUNT_ID,
  SNAPSHOT_DATE,
  (EFFECTIVE_LIMIT * UTILISATION)::NUMBER(14,2),
  EFFECTIVE_LIMIT::NUMBER(12,2),
  GREATEST(EFFECTIVE_LIMIT - EFFECTIVE_LIMIT * UTILISATION, 0)::NUMBER(14,2),
  GREATEST(EFFECTIVE_LIMIT * UTILISATION * 0.08, 25)::NUMBER(12,2),
  GREATEST(EFFECTIVE_LIMIT * UTILISATION * 0.025, 15)::NUMBER(12,2),
  DAYS_PAST_DUE_RAW::NUMBER(4,0),
  IFF(DAYS_PAST_DUE_RAW = 0, 0,
      GREATEST(EFFECTIVE_LIMIT * UTILISATION * 0.025, 15))::NUMBER(12,2),
  CASE
    WHEN DAYS_PAST_DUE_RAW >= 120 THEN 'CHARGED_OFF'
    WHEN DAYS_PAST_DUE_RAW > 0 THEN 'DELINQUENT'
    ELSE 'CURRENT'
  END,
  IFF(SNAPSHOT_DATE >= '{{DRIFT_START_DATE}}'::DATE, 'DRIFT', 'STABLE'),
  '{{AS_OF_DATE}} 00:00:00'::TIMESTAMP_NTZ
FROM states;

CREATE OR REPLACE TABLE FACT_PAYMENT (
  PAYMENT_ID VARCHAR COMMENT 'Unique payment transaction identifier; primary event key',
  ACCOUNT_ID VARCHAR COMMENT 'Facility identifier joining to DIM_CREDIT_ACCOUNT',
  PAYMENT_DATE DATE COMMENT 'Date the payment was posted',
  PAYMENT_AMOUNT NUMBER(12,2) COMMENT 'Posted amount in account currency units; zero for a missed payment',
