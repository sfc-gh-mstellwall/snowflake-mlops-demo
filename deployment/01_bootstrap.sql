  PAYMENT_CHANNEL VARCHAR COMMENT 'Payment channel: DIRECT_DEBIT, DIGITAL, or BRANCH',
  GENERATED_AT TIMESTAMP_NTZ COMMENT 'Timestamp when the source record was generated'
) COMMENT = 'One row per scheduled facility payment event at approximately monthly cadence';

INSERT OVERWRITE INTO FACT_PAYMENT
WITH monthly_due AS (
  SELECT s.*, a.BILLING_CYCLE_DAY
  FROM FACT_ACCOUNT_DAILY_SNAPSHOT s
  JOIN DIM_CREDIT_ACCOUNT a USING (ACCOUNT_ID)
  WHERE DAY(s.SNAPSHOT_DATE) = a.BILLING_CYCLE_DAY
)
SELECT
  'PMT-' || SUBSTR(ACCOUNT_ID, 6) || '-' || TO_CHAR(SNAPSHOT_DATE, 'YYYYMMDD'),
  ACCOUNT_ID,
  SNAPSHOT_DATE,
  CASE
    WHEN DAYS_PAST_DUE >= 30 THEN 0
    WHEN DAYS_PAST_DUE > 0 THEN MINIMUM_PAYMENT_DUE * 0.60
    ELSE GREATEST(MINIMUM_PAYMENT_DUE,
         OUTSTANDING_BALANCE * (0.04 + MOD(BITAND(HASH(ACCOUNT_ID, SNAPSHOT_DATE, {{DATA_SEED}} + 41), 9223372036854775807), 700) / 10000.0))
  END::NUMBER(12,2),
  CASE WHEN DAYS_PAST_DUE >= 30 THEN 'MISSED'
       WHEN DAYS_PAST_DUE > 0 THEN 'LATE' ELSE 'POSTED' END,
  CASE MOD(BITAND(HASH(ACCOUNT_ID, SNAPSHOT_DATE, {{DATA_SEED}} + 43), 9223372036854775807), 3)
    WHEN 0 THEN 'DIRECT_DEBIT' WHEN 1 THEN 'DIGITAL' ELSE 'BRANCH' END,
  '{{AS_OF_DATE}} 00:00:00'::TIMESTAMP_NTZ
FROM monthly_due;

