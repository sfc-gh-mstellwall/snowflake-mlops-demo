UPDATE DIM_CREDIT_ACCOUNT a
SET ACCOUNT_STATUS = latest.ACCOUNT_STATUS
FROM (
  SELECT ACCOUNT_ID, ACCOUNT_STATUS
  FROM FACT_ACCOUNT_DAILY_SNAPSHOT
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ACCOUNT_ID ORDER BY SNAPSHOT_DATE DESC) = 1
) latest
WHERE a.ACCOUNT_ID = latest.ACCOUNT_ID;

CREATE OR REPLACE TABLE ACCOUNT_OBSERVATION (
  ACCOUNT_ID VARCHAR COMMENT 'Facility identifier evaluated at an observation date',
  OBSERVATION_DATE DATE COMMENT 'Month-start date at which prediction-time features are retrieved',
  OUTCOME_FINALITY_DATE DATE COMMENT 'Date the forward 90-day outcome window becomes complete',
  DEFAULT_WITHIN_90D NUMBER(1,0) COMMENT 'One when first default occurs after observation and within 90 days',
  OUTCOME_STATUS VARCHAR COMMENT 'FINALISED when the full horizon is observable; otherwise PENDING',
  GENERATED_AT TIMESTAMP_NTZ COMMENT 'Timestamp when the observation record was generated'
) COMMENT = 'One row per at-risk facility and monthly observation date with a delayed 90-day outcome';

INSERT OVERWRITE INTO ACCOUNT_OBSERVATION
WITH months AS (
  SELECT DATEADD(MONTH, MONTH_NUMBER, '{{FIRST_OBSERVATION_MONTH}}'::DATE) AS OBSERVATION_DATE
  FROM (
    SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS MONTH_NUMBER
    FROM TABLE(GENERATOR(ROWCOUNT => {{OBSERVATION_MONTHS}}))
  )
)
SELECT
  a.ACCOUNT_ID,
  m.OBSERVATION_DATE,
  DATEADD(DAY, {{OUTCOME_WINDOW_DAYS}}, m.OBSERVATION_DATE)::DATE,
  IFF(
    DATEADD(DAY, {{OUTCOME_WINDOW_DAYS}}, m.OBSERVATION_DATE) <= '{{AS_OF_DATE}}'::DATE,
    IFF(d.DEFAULT_DATE > m.OBSERVATION_DATE
        AND d.DEFAULT_DATE <= DATEADD(DAY, {{OUTCOME_WINDOW_DAYS}}, m.OBSERVATION_DATE), 1, 0),
    NULL
  ),
  IFF(DATEADD(DAY, {{OUTCOME_WINDOW_DAYS}}, m.OBSERVATION_DATE) <= '{{AS_OF_DATE}}'::DATE,
      'FINALISED', 'PENDING'),
  '{{AS_OF_DATE}} 00:00:00'::TIMESTAMP_NTZ
FROM DIM_CREDIT_ACCOUNT a
CROSS JOIN months m
LEFT JOIN FACT_DEFAULT_EVENT d USING (ACCOUNT_ID)
WHERE d.DEFAULT_DATE IS NULL OR d.DEFAULT_DATE > m.OBSERVATION_DATE;

