-- Review declared grains and source coverage.
SELECT 'DIM_CUSTOMER' AS OBJECT_NAME, COUNT(*) AS RECORD_COUNT,
  COUNT(DISTINCT CUSTOMER_ID) AS DISTINCT_KEY_COUNT
FROM {{RAW_SCHEMA}}.DIM_CUSTOMER
UNION ALL
SELECT 'DIM_CREDIT_ACCOUNT', COUNT(*), COUNT(DISTINCT ACCOUNT_ID)
FROM {{RAW_SCHEMA}}.DIM_CREDIT_ACCOUNT
UNION ALL
SELECT 'FACT_CUSTOMER_FINANCIAL_SNAPSHOT', COUNT(*),
  COUNT(DISTINCT CUSTOMER_ID || '|' || SNAPSHOT_DATE::VARCHAR)
FROM {{RAW_SCHEMA}}.FACT_CUSTOMER_FINANCIAL_SNAPSHOT
UNION ALL
SELECT 'FACT_ACCOUNT_DAILY_SNAPSHOT', COUNT(*),
  COUNT(DISTINCT ACCOUNT_ID || '|' || SNAPSHOT_DATE::VARCHAR)
FROM {{RAW_SCHEMA}}.FACT_ACCOUNT_DAILY_SNAPSHOT
UNION ALL
SELECT 'FACT_PAYMENT', COUNT(*), COUNT(DISTINCT PAYMENT_ID)
FROM {{RAW_SCHEMA}}.FACT_PAYMENT
UNION ALL
SELECT 'FACT_CUSTOMER_CONTACT', COUNT(*), COUNT(DISTINCT CONTACT_ID)
FROM {{RAW_SCHEMA}}.FACT_CUSTOMER_CONTACT
UNION ALL
SELECT 'FACT_ACCOUNT_EVENT', COUNT(*), COUNT(DISTINCT EVENT_ID)
FROM {{RAW_SCHEMA}}.FACT_ACCOUNT_EVENT
UNION ALL
SELECT 'FACT_DEFAULT_EVENT', COUNT(*), COUNT(DISTINCT ACCOUNT_ID)
FROM {{RAW_SCHEMA}}.FACT_DEFAULT_EVENT
UNION ALL
SELECT 'ACCOUNT_OBSERVATION', COUNT(*),
  COUNT(DISTINCT ACCOUNT_ID || '|' || OBSERVATION_DATE::VARCHAR)
FROM {{RAW_SCHEMA}}.ACCOUNT_OBSERVATION
ORDER BY OBJECT_NAME;

-- Daily history must include at least twelve warm-up months before modelling starts.
SELECT MIN(SNAPSHOT_DATE) AS FIRST_DAILY_SNAPSHOT,
  MAX(SNAPSHOT_DATE) AS LAST_DAILY_SNAPSHOT,
  DATEDIFF(DAY, MIN(SNAPSHOT_DATE), '{{FIRST_OBSERVATION_MONTH}}'::DATE)
    AS WARMUP_DAYS,
  COUNT(DISTINCT SNAPSHOT_DATE) AS CALENDAR_DAYS
FROM {{RAW_SCHEMA}}.FACT_ACCOUNT_DAILY_SNAPSHOT;

-- Labels must be delayed, censored by the simulated as-of date, and non-trivial.
SELECT OUTCOME_STATUS,
  COUNT(*) AS OUTCOME_COUNT,
  COUNT_IF(DEFAULT_WITHIN_90D = 1) AS DEFAULT_COUNT,
  AVG(DEFAULT_WITHIN_90D) AS DEFAULT_RATE,
  MIN(OBSERVATION_DATE) AS FIRST_OBSERVATION,
  MAX(OBSERVATION_DATE) AS LAST_OBSERVATION,
  MAX(OUTCOME_FINALITY_DATE) AS LATEST_FINALITY_DATE
FROM {{RAW_SCHEMA}}.ACCOUNT_OBSERVATION
GROUP BY OUTCOME_STATUS
ORDER BY OUTCOME_STATUS;

-- Controlled drift should be visible in prediction-time source facts.
SELECT DATA_SCENARIO,
  COUNT(*) AS DAILY_RECORD_COUNT,
  AVG(DIV0(OUTSTANDING_BALANCE, CREDIT_LIMIT)) AS AVG_UTILISATION,
  AVG(DAYS_PAST_DUE) AS AVG_DAYS_PAST_DUE,
  AVG(IFF(ACCOUNT_STATUS = 'DELINQUENT', 1, 0)) AS DELINQUENCY_RATE
FROM {{RAW_SCHEMA}}.FACT_ACCOUNT_DAILY_SNAPSHOT
GROUP BY DATA_SCENARIO
ORDER BY DATA_SCENARIO;

