-- View joining durable batch predictions to 90-day outcomes without treating pending rows as negative (0)
CREATE OR REPLACE VIEW {{DATABASE}}.{{CONTROL_SCHEMA}}.V_PREDICTION_OUTCOME_MATURITY AS
SELECT
  p.PREDICTION_ID,
  p.BATCH_ID,
  p.ACCOUNT_ID,
  p.OBSERVATION_DATE,
  p.SCORED_AT,
  p.MODEL_DATABASE,
  p.MODEL_SCHEMA,
  p.MODEL_NAME,
  p.MODEL_VERSION,
  p.RELEASE_ID,
  p.SCORE,
  p.PREDICTION_CLASS,
  p.FEATURE_CONTRACT,
  o.OUTCOME_FINALITY_DATE,
  CASE
    WHEN o.ACCOUNT_ID IS NULL THEN 'UNMATCHED'
    WHEN o.OUTCOME_STATUS = 'PENDING' THEN 'PENDING'
    ELSE 'FINAL'
  END AS LABEL_MATURITY_STATUS,
  CASE
    WHEN o.OUTCOME_STATUS = 'FINALISED' THEN o.DEFAULT_WITHIN_90D
    ELSE NULL
  END AS MATURED_DEFAULT_WITHIN_90D
FROM {{DATABASE}}.{{CONTROL_SCHEMA}}.PREDICTION_RECORD p
LEFT JOIN {{DATABASE}}.{{RAW_SCHEMA}}.ACCOUNT_OBSERVATION o
  ON p.ACCOUNT_ID = o.ACCOUNT_ID
 AND p.OBSERVATION_DATE = o.OBSERVATION_DATE;

GRANT SELECT ON VIEW {{DATABASE}}.{{CONTROL_SCHEMA}}.V_PREDICTION_OUTCOME_MATURITY
  TO ROLE {{DEVELOPER_ROLE}};
GRANT SELECT ON VIEW {{DATABASE}}.{{CONTROL_SCHEMA}}.V_PREDICTION_OUTCOME_MATURITY
  TO ROLE {{ENGINEER_ROLE}};
GRANT SELECT ON VIEW {{DATABASE}}.{{CONTROL_SCHEMA}}.V_PREDICTION_OUTCOME_MATURITY
  TO ROLE {{PROD_OWNER_ROLE}};
GRANT SELECT ON VIEW {{DATABASE}}.{{CONTROL_SCHEMA}}.V_PREDICTION_OUTCOME_MATURITY
  TO ROLE {{SERVICE_ROLE}};

